"""A Markdown reference of the AUX protocol as celestron-aux knows it.

Everything comes from the catalog (built-in names, plus your own when a user
catalog is in use) and the payload decoders, so the reference never drifts from
the code. ``docs/protocol.md`` in the repository is this module's output with
the built-in names only; a test checks that it is up to date.
"""

from __future__ import annotations

import inspect
import re
from pathlib import Path
from typing import Dict, List, Optional

from . import catalog, decoding
from .protocol.packets import AUX_PREAMBLE, STARSENSE_PREAMBLE

# Inline comments in the catalog's command tables, e.g. ``0x01: "NAME",  # note``.
_NOTE = re.compile(r'0x[0-9A-Fa-f]{2}:\s*"([A-Z0-9_]+)",?\s*#\s*(.+)$')


def _notes() -> Dict[str, str]:
    """Notes on commands, taken from the comments next to them in catalog.py."""
    notes: Dict[str, str] = {}
    for line in inspect.getsource(catalog).splitlines():
        match = _NOTE.search(line)
        if match:
            notes.setdefault(match.group(1), match.group(2).strip())
    return notes


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _role(address: int) -> str:
    if address == catalog.Addr.SCANNER:
        return "this tool"
    if address in catalog.CONTROLLERS:
        return "controller"
    if address in catalog.MOTOR_CLIENTS:
        return "accessory that also drives the motors"
    return "device"


def _is_yours(device: int, command: Optional[int], name: str) -> bool:
    user = catalog.user_catalog()
    if command is None:
        return user.device(device) == name
    return user.commands(device).get(command) == name


def markdown() -> str:
    """The reference, as Markdown."""
    notes = _notes()
    decoded = set(decoding._DECODERS)
    generic = sorted(catalog.GENERIC_COMMANDS.items())
    lines: List[str] = [
        "# Celestron AUX protocol reference",
        "",
        "Generated by celestron-aux (`celestron-aux --export-docs`) from its catalog "
        "and payload decoders. Names come from captures of real devices and community reverse "
        "engineering, not from Celestron documentation.",
        "",
        "## Frames",
        "",
        f"* **AUX packet**: `{AUX_PREAMBLE:02X} | len | src | dst | cmd | data... | checksum`. "
        "`len` counts `src`, `dst`, `cmd` and the data bytes. The checksum is the two's complement "
        "of the sum of every byte from `len` through the last data byte.",
        f"* **StarSense bulk frame**: `{STARSENSE_PREAMBLE:02X} | len (4 bytes, big-endian) | "
        "payload... | checksum`, with every `3B` in the length and payload escaped as `3B 02 02`. "
        "The payload is a star list, 8 bytes per star.",
        "",
        "A command number belongs to the device a packet is about: in a packet between a "
        "controller (a hand controller, CPWI, this tool) and a device, that is the device, "
        "in both the request and the reply. The StarSense AutoGuider's packets to the motors use "
        "the motors' commands.",
        "",
        "## Devices",
        "",
        "| Address | Name | Role |",
        "| --- | --- | --- |",
    ]
    addresses = catalog.known_addresses()
    for address in addresses:
        name = catalog.device_name(address)
        mine = " (your name)" if _is_yours(address, None, name) else ""
        lines.append(f"| `0x{address:02X}` | {_cell(name)}{mine} | {_role(address)} |")
    lines += [
        "",
        "## Commands every device answers",
        "",
        "| Command | Name | Payload decoded |",
        "| --- | --- | --- |",
    ]
    lines += [f"| `0x{c:02X}` | {_cell(n)} | {'yes' if (decoding.ANY_DEVICE, c) in decoded else ''} |"
              for c, n in generic]
    lines += ["", "A device's own table below may give these a more specific name.", ""]
    lines += ["## Commands by device", ""]
    shown = [(a, [(c, n) for c, n in catalog.commands_for(a)
                  if catalog.GENERIC_COMMANDS.get(c) != n]) for a in range(0x100)]
    shown = [(a, commands) for a, commands in shown if commands]
    seen: Dict[tuple, int] = {}
    for address, commands in shown:
        lines += [f"### `0x{address:02X}` {_cell(catalog.device_name(address))}", ""]
        key = tuple(commands)
        if key in seen and len(commands) > 1:
            lines += [f"Same commands as `0x{seen[key]:02X}` {_cell(catalog.device_name(seen[key]))}.", ""]
            continue
        seen.setdefault(key, address)
        lines += ["| Command | Name | Payload decoded | Notes |", "| --- | --- | --- | --- |"]
        for command, name in commands:
            mark = " (your name)" if _is_yours(address, command, name) else ""
            is_decoded = (address, command) in decoded or (decoding.ANY_DEVICE, command) in decoded
            lines.append(f"| `0x{command:02X}` | {_cell(name)}{mark} | {'yes' if is_decoded else ''} "
                         f"| {_cell(notes.get(name, ''))} |")
        lines.append("")
    lines += [
        "## Mount models",
        "",
        "Answered by `MTR_GET_MODEL` (0x05) on the AZM/RA motor (0x10).",
        "",
        "| Model id | Mount |",
        "| --- | --- |",
    ]
    lines += [f"| `0x{m:04X}` | {_cell(n)} |" for m, n in sorted(catalog.MOUNT_MODELS.items())]
    lines += [
        "",
        "When the exact id is unknown, its first byte gives the family:",
        "",
        "| First byte | Family |",
        "| --- | --- |",
    ]
    lines += [f"| `0x{f:02X}` | {_cell(n)} |" for f, n in sorted(catalog.MOUNT_FAMILIES.items())]
    return "\n".join(lines) + "\n"


def write_markdown(destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(markdown(), encoding="utf-8")
